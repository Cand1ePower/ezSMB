"""Fetch only the Material outline vectors used by the app (Apache-2.0)."""
import concurrent.futures, pathlib, subprocess, xml.etree.ElementTree as ET
root = pathlib.Path(__file__).resolve().parents[1]
icons = {
    'ArrowBack': 'navigation/arrow_back', 'InsertDriveFile': 'editor/insert_drive_file',
    'Refresh': 'navigation/refresh', 'MoreVert': 'navigation/more_vert',
    'Upload': 'file/upload', 'FolderOpen': 'file/folder_open', 'Folder': 'file/folder',
    'ChevronRight': 'navigation/chevron_right', 'Download': 'file/download',
    'Computer': 'hardware/computer', 'Add': 'content/add', 'Devices': 'device/devices',
    'FolderShared': 'file/folder_shared', 'VisibilityOff': 'action/visibility_off', 'Visibility': 'action/visibility',
}
out = root / '.tools' / 'icons'; out.mkdir(parents=True, exist_ok=True)
def fetch(item):
    name, path = item
    file = out / (name + '.svg')
    subprocess.run(['curl.exe', '-sSfL', '--retry', '2', '--max-time', '30', '-o', str(file), f'https://raw.githubusercontent.com/google/material-design-icons/master/src/{path}/materialiconsoutlined/24px.svg'], check=True)
    paths = [p.attrib['d'] for p in ET.parse(file).getroot().iter() if p.tag.endswith('path') and p.attrib.get('fill') != 'none']
    assert paths
    return name, paths
with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
    vectors = list(pool.map(fetch, icons.items()))
code = '''// Material Design Icons, Google LLC, Apache-2.0. Generated by tools/generate_icons.py.
package com.ezsmb.app
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

object EzIcons {
    private fun vector(name: String, mirrored: Boolean, vararg paths: String) = ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f, autoMirror = mirrored).apply {
        paths.forEach { addPath(PathParser().parsePathString(it).toNodes(), fill = SolidColor(Color.Black)) }
    }.build()
'''
for name, paths in vectors:
    args = ', '.join('"' + p + '"' for p in paths)
    code += f'    val {name} by lazy {{ vector("{name}", {str(name in ("ArrowBack", "ChevronRight")).lower()}, {args}) }}\n'
code += '}\n'
(root / 'app/src/main/java/com/ezsmb/app/EzIcons.kt').write_text(code, encoding='utf-8')
activity = root / 'app/src/main/java/com/ezsmb/app/MainActivity.kt'
text = activity.read_text(encoding='utf-8')
text = '\n'.join(line for line in text.splitlines() if not line.startswith('import androidx.compose.material.icons.')) + '\n'
text = text.replace('Icons.AutoMirrored.Outlined.', 'EzIcons.').replace('Icons.Outlined.', 'EzIcons.')
activity.write_text(text, encoding='utf-8')
